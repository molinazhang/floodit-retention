#!/usr/bin/env python
"""
make_synthetic_data.py - SYNTHETIC smoke-test data. Not derived from the Flood-It! export.

Purpose: let analysis.py / ml_day0_model.py / experiment_power.py run end to end before
BigQuery results exist, and prove the figure code works. The generating process is made up
(a simple logistic model of return probability); every output it feeds is written to
data/synthetic/ and figures_synthetic_smoke/, watermarked, and must never be quoted.

    python python/make_synthetic_data.py [--n 8000 --seed 1]
"""
import argparse
import pathlib

import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=8000)
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    n = args.n
    cohort_date = pd.to_datetime("2018-06-12") + pd.to_timedelta(rng.integers(0, 107, n), unit="D")
    platform = rng.choice(["ANDROID", "IOS"], n, p=[0.6, 0.4])
    started = rng.random(n) < 0.78
    levels_started = np.where(started, rng.poisson(3.2, n) + 1, 0)
    completed = np.minimum(levels_started, rng.binomial(levels_started, 0.55))
    failed = np.minimum(levels_started - completed, rng.binomial(np.maximum(levels_started - completed, 0), 0.7))
    engagement = np.where(started, rng.gamma(2.0, 180, n), rng.gamma(1.2, 40, n))
    logit = -2.3 + 0.35 * np.log1p(completed) + 0.12 * np.log1p(engagement / 60) - 0.15 * (failed > 0) + 0.1 * (platform == "IOS")
    p7 = 1 / (1 + np.exp(-logit))
    retained_d7 = rng.random(n) < p7
    retained_d1 = rng.random(n) < np.clip(p7 * 2.2, 0, 0.9)
    first_outcome = np.where(~started, "not_started",
                     np.where(completed > 0, "level_complete", np.where(failed > 0, "level_fail", "started_no_outcome")))
    df = pd.DataFrame({
        "user_pseudo_id": [f"SYN{i:07d}" for i in range(n)],
        "cohort_date": cohort_date.date, "cohort_week": (cohort_date - pd.to_timedelta(cohort_date.weekday, unit="D")).date,
        "phase": np.where(cohort_date <= pd.Timestamp("2018-08-03"), "exploratory", "validation"),
        "platform": platform, "device_category": "mobile", "os": np.where(platform == "IOS", "iOS", "Android"),
        "country": rng.choice(["United States", "India", "Brazil", "<Other>"], n), "language": "en-us", "app_version": "2.0",
        "traffic_source": "(direct)", "traffic_medium": "(none)", "first_open_hour_utc": rng.integers(0, 24, n),
        "first_open_is_first_seen": True, "first_touch_consistent": True, "complete_followup": True, "in_cohort_window": True,
        "window_coverage_ok": True, "eligible": True,
        "retained_d1": retained_d1, "retained_d7": retained_d7, "retained_d1_gameplay": retained_d1 & (rng.random(n) < 0.8),
        "retained_d7_gameplay": retained_d7 & (rng.random(n) < 0.8), "active_days_d1_d7": rng.binomial(7, p7),
        "app_removed_d0_d7": rng.random(n) < 0.08,
        "d0_n_events": levels_started * 4 + 6, "d0_active_events": levels_started * 3 + 2, "d0_gameplay_events": levels_started * 3,
        "d0_engagement_sec": engagement.round(1), "d0_sessions": rng.poisson(1.3, n) + 1,
        "d0_levels_started": levels_started, "d0_levels_completed": completed, "d0_levels_failed": failed,
        "d0_levels_reset": rng.poisson(0.2, n), "d0_levels_retried": rng.poisson(0.3, n), "d0_extra_steps": rng.poisson(0.4, n) * started,
        "d0_no_more_extra_steps": rng.poisson(0.05, n), "d0_ad_rewards": rng.poisson(0.2, n), "d0_post_scores": completed,
        "d0_economy_events": rng.poisson(0.1, n), "d0_social_events": rng.poisson(0.02, n), "d0_hit_5_levels": completed >= 5,
        "d0_app_removed": rng.random(n) < 0.03, "d0_max_score": np.where(completed > 0, rng.integers(100, 5000, n), np.nan),
        "d0_active_span_sec": (engagement * 1.5).round(0), "d0_secs_to_first_level": np.where(started, rng.gamma(1.5, 40, n).round(0), np.nan),
        "d0_first_level_outcome": first_outcome,
    })
    df["behavior_group"] = np.select([levels_started == 0, completed == 0, completed <= 2],
                                     ["A_no_level_started", "B_started_none_completed", "C_completed_1_to_2"], "D_completed_3_plus")
    df["first_level_group"] = np.select([~started, completed > 0, failed > 0], ["not_started", "first_level_completed", "first_level_failed"], "started_no_outcome")
    df["SYNTHETIC"] = True
    out = ROOT / "data" / "synthetic" / "synthetic_user_level.csv"
    df.to_csv(out, index=False)
    (ROOT / "data" / "synthetic" / "README.md").write_text(
        "# SYNTHETIC smoke-test data\n\nGenerated by python/make_synthetic_data.py from a made-up process. "
        "Used only to verify that the analysis scripts run. Not a result; never cite.\n")
    print(f"wrote {out} ({len(df)} rows) - SYNTHETIC")


if __name__ == "__main__":
    main()
